#!/bin/bash
# =============================================================================
# Главный сценарий миграции Home Assistant с 192.168.1.103 на 192.168.1.91
# =============================================================================
# ВНИМАНИЕ: Этот скрипт НЕ выполняет удалённые действия сам.
# Он показывает последовательность шагов и пути к скриптам, которые нужно
# запускать на соответствующих машинах вручную (по SSH).
#
# Требуется: SSH-доступ по ключам к alex@192.168.1.103 и alex@192.168.1.91
# =============================================================================

echo "=================================================================="
echo "  МИГРАЦИЯ HOME ASSISTANT: .103 -> .91"
echo "=================================================================="
echo ""
echo "Требуемые предусловия:"
echo "  1. SSH-ключи настроены: alex@192.168.1.103 и alex@192.168.1.91"
echo "  2. Вы работаете с машины, имеющей доступ к обоим серверам по SSH"
echo ""

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "------------------------------------------------------------------------"
echo "  ЭТАП 0 — Подготовка (на .103)"
echo "------------------------------------------------------------------------"
echo "1. Убедиться в SSH доступе:"
echo "   ssh alex@192.168.1.103  (должно входить без пароля)"
echo "   ssh alex@192.168.1.91   (должно входить без пароля)"
echo ""
echo "2. Посмотреть существующий скрипт зеркалирования на .103:"
echo "   ssh alex@192.168.1.103 'cat /usr/local/bin/ha_mirror_to_91.sh'"
echo ""

echo "------------------------------------------------------------------------"
echo "  ЭТАП 1 — Бэкап и удаление старого HA (на .91)"
echo "------------------------------------------------------------------------"
echo "Запустить на .91:"
echo "  scp $SCRIPT_DIR/backup_remove_ha_91.sh alex@192.168.1.91:/home/alex/"
echo "  ssh alex@192.168.1.91 'chmod +x /home/alex/backup_remove_ha_91.sh && /home/alex/backup_remove_ha_91.sh'"
echo ""

echo "------------------------------------------------------------------------"
echo "  ЭТАП 2 — Копирование конфигурации (.103 -> .91)"
echo "------------------------------------------------------------------------"
echo "Запустить на .103 (или с управляющей машины):"
echo "  scp $SCRIPT_DIR/copy_config_103_to_91.sh alex@192.168.1.103:/home/alex/"
echo "  ssh alex@192.168.1.103 'chmod +x /home/alex/copy_config_103_to_91.sh && /home/alex/copy_config_103_to_91.sh'"
echo ""

echo "------------------------------------------------------------------------"
echo "  ЭТАП 3 — Установка нового HA на .91 (Docker)"
echo "------------------------------------------------------------------------"
echo "Запустить на .91:"
echo "  scp $SCRIPT_DIR/install_ha_91.sh alex@192.168.1.91:/home/alex/"
echo "  ssh alex@192.168.1.91 'chmod +x /home/alex/install_ha_91.sh && /home/alex/install_ha_91.sh'"
echo ""

echo "------------------------------------------------------------------------"
echo "  ЭТАП 4 — Правка конфигурации под .91"
echo "------------------------------------------------------------------------"
echo "Запустить на .91:"
echo "  scp $SCRIPT_DIR/fix_config_91.sh alex@192.168.1.91:/home/alex/"
echo "  ssh alex@192.168.1.91 'chmod +x /home/alex/fix_config_91.sh && /home/alex/fix_config_91.sh'"
echo ""

echo "------------------------------------------------------------------------"
echo "  ЭТАП 5 — Проверка и приёмка"
echo "------------------------------------------------------------------------"
echo "1. Открыть браузер: http://192.168.1.91:8123"
echo "2. Проверить логи: ssh alex@192.168.1.91 'docker logs homeassistant'"
echo "3. Проверить MQTT: подключение к брокеру 192.168.1.23:1883"
echo "4. Проверить сенсоры ym/*, esp/state"
echo ""

echo "------------------------------------------------------------------------"
echo "  ГОТОВЫЕ СКРИПТЫ в $SCRIPT_DIR:"
echo "------------------------------------------------------------------------"
ls -la "$SCRIPT_DIR"/*.sh 2>/dev/null || echo "  (скрипты не найдены)"
echo ""
echo "=================================================================="
echo "  После выполнения всех этапов HA с конфигурацией с .103 будет"
echo "  запущен на .91 с настройками, скорректированными под .91."
echo "=================================================================="